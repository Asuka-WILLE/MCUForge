// 通用串口接收：有多少收多少，返回实际收到的字节数
int RS485_Receive_All(uint8_t *buf, uint8_t max_len, uint32_t timeout)
{
    uint8_t len = 0;
    uint32_t tick_start = HAL_GetTick();

    while (len < max_len && (HAL_GetTick() - tick_start) < timeout)
    {
        if (HAL_UART_Receive(&huart2, &buf[len], 1, 5) == HAL_OK)
        {
            len++;
            tick_start = HAL_GetTick(); // 收到就刷新超时
        }
    }
    return len;
}



